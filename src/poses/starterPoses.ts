import { POSE_CATEGORIES, POSE_TAGS, type Pose, type PoseCategory, type PoseDifficulty, type PoseTag } from '../data/types';

/**
 * The starter library (PL3): about 60 poses, shipped with the app and seeded into
 * the `poses` table on first run (see `seedStarterPoses` in src/data/repo.ts).
 * The illustrations live in public/poses and are precached for offline use.
 */

export { POSE_CATEGORIES, POSE_TAGS };

const DIFFICULTY: Record<1 | 2 | 3, PoseDifficulty> = { 1: 'easy', 2: 'medium', 3: 'hard' };

/** Pose ids are stable slugs, so seeding twice or updating the library never duplicates. */
function pose(
  id: string,
  name: string,
  category: PoseCategory,
  people: [number, number],
  difficulty: 1 | 2 | 3,
  tags: PoseTag[],
  description: string,
  directions: string[],
  allTips: string[],
): Pose {
  const isMistake = (t: string) => /^common mistake:/i.test(t);
  return {
    id,
    createdAt: 0,
    updatedAt: 0,
    name,
    category,
    minSize: people[0],
    maxSize: people[1],
    description,
    directions,
    tips: allTips.filter((t) => !isMistake(t)),
    mistakes: allTips.filter(isMistake).map((t) => t.replace(/^common mistake:\s*/i, '')),
    tags,
    difficulty: DIFFICULTY[difficulty],
    favorite: false,
    builtIn: true,
    image: `poses/${id}.svg`,
    imageCredit: { source: 'Photo Planner', licence: 'Original illustration, made for this app' },
  };
}

